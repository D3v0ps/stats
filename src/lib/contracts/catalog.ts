import type { DatasetKind, MetricKind, SnapshotRollup, Unit } from "./domain";

export interface CatalogDataset {
  key: string;
  name: string;
  kind: DatasetKind;
  dimensions: string[];
}

export interface CatalogDimension {
  key: string;
  label: string;
  personal: boolean;
  /** ask = unknown values are flagged in review; auto_create = new values are added silently. */
  unknownPolicy: "ask" | "auto_create";
}

export interface CatalogMetric {
  key: string;
  name: string;
  unit: Unit;
  kind: MetricKind;
  datasetKey: string | null;
  higherIsBetter: boolean | null;
  decimals: number | null;
  description: string;
  /** Definite-form subject for generated headlines ("DELTAGARNA ÖKAR."). */
  headlineSubject: string;
  snapshotRollup?: SnapshotRollup;
  baseMetricKey?: string;
  distinctDimension?: string;
  accountGroupKey?: string;
  formula?: string;
}

export interface CatalogAccountGroup {
  key: string;
  name: string;
  sign: 1 | -1;
  ranges: { from: number; to: number }[];
}

