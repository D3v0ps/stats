-- Reference data: companies, catalog (datasets, dimensions, metrics, account groups)
-- and settings. Seeded in 0009_seed.sql from src/lib/contracts/catalog.ts.

create table public.companies (
  id smallint primary key,
  code text not null unique check (code in ('MBAB', 'MBR')),
  legal_name text not null,
  short_name text not null,
  org_nr text not null unique,
  fiscal_start_month smallint not null default 1 check (fiscal_start_month between 1 and 12)
);

create table public.datasets (
  id smallint generated by default as identity primary key,
  key text not null unique check (key ~ '^[a-z][a-z0-9_]{1,40}$'),
  name text not null,
  kind text not null check (kind in ('table', 'cases', 'ledger'))
);

create table public.dimensions (
  id smallint generated by default as identity primary key,
  key text not null unique check (key ~ '^[a-z][a-z0-9_]{1,40}$' and key <> 'bolag'),
  label text not null,
  is_personal boolean not null default false,
  unknown_policy text not null default 'ask' check (unknown_policy in ('ask', 'auto_create'))
);

create table public.dataset_dimensions (
  dataset_id smallint not null references public.datasets (id) on delete cascade,
  dimension_id smallint not null references public.dimensions (id),
  primary key (dataset_id, dimension_id)
);
create index dataset_dimensions_dimension_idx on public.dataset_dimensions (dimension_id);

create table public.dimension_values (
  id bigint generated by default as identity primary key,
  dimension_id smallint not null references public.dimensions (id),
  code text not null check (code <> ''),
  label text not null check (label <> ''),
  sort integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (dimension_id, code),
  -- Target of the composite FK from dimension_aliases (alias and value share a dimension).
  unique (id, dimension_id)
);
create trigger dimension_values_no_personnummer
  before insert or update of code, label on public.dimension_values
  for each row execute function private.reject_personnummer('code', 'label');

create table public.dimension_aliases (
  dimension_id smallint not null references public.dimensions (id),
  alias_norm text not null check (alias_norm <> ''),
  value_id bigint not null,
  primary key (dimension_id, alias_norm),
  foreign key (value_id, dimension_id) references public.dimension_values (id, dimension_id)
    on delete cascade
);
create index dimension_aliases_value_idx on public.dimension_aliases (value_id, dimension_id);

-- Aliases are stored normalized whatever the client sends.
create or replace function private.normalize_alias()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.alias_norm := private.normalize_label(new.alias_norm);
  return new;
end;
$$;
create trigger dimension_aliases_a_normalize
  before insert or update of alias_norm on public.dimension_aliases
  for each row execute function private.normalize_alias();
create trigger dimension_aliases_b_no_personnummer
  before insert or update of alias_norm on public.dimension_aliases
  for each row execute function private.reject_personnummer('alias_norm');

create table public.account_groups (
  key text primary key check (key ~ '^[a-z][a-z0-9_]{1,40}$'),
  name text not null,
  sign smallint not null check (sign in (1, -1)),
  sort integer not null default 0
);

create table public.account_group_ranges (
  id integer generated by default as identity primary key,
  group_key text not null references public.account_groups (key) on update cascade on delete cascade,
  from_account integer not null check (from_account between 1000 and 9999),
  to_account integer not null check (to_account between 1000 and 9999),
  check (from_account <= to_account)
);
create index account_group_ranges_group_idx on public.account_group_ranges (group_key);

create table public.metrics (
  id smallint generated by default as identity primary key,
  key text not null unique check (key ~ '^[a-z][a-z0-9_]{1,60}$'),
  name text not null,
  unit text not null check (unit in ('st', 'kr', 'h', 'pct', 'faktor', 'man')),
  kind text not null check (kind in ('sum', 'snapshot', 'distinct', 'ledger', 'formula')),
  dataset_id smallint references public.datasets (id),
  higher_is_better boolean,
  decimals smallint check (decimals between 0 and 6),
  description text,
  headline_subject text,
  snapshot_rollup text check (snapshot_rollup in ('last', 'avg')),
  base_metric_id smallint references public.metrics (id),
  distinct_dimension_id smallint references public.dimensions (id),
  account_group_key text references public.account_groups (key) on update cascade,
  formula text check (formula <> ''),
  is_system boolean not null default false,
  constraint metrics_sum_shape check (
    kind <> 'sum' or (dataset_id is not null and snapshot_rollup is null and base_metric_id is null
      and distinct_dimension_id is null and account_group_key is null and formula is null)
  ),
  constraint metrics_snapshot_shape check (
    kind <> 'snapshot' or (dataset_id is not null and snapshot_rollup is not null
      and base_metric_id is null and distinct_dimension_id is null and account_group_key is null
      and formula is null)
  ),
  constraint metrics_distinct_shape check (
    kind <> 'distinct' or (dataset_id is not null and base_metric_id is not null
      and distinct_dimension_id is not null and snapshot_rollup is null
      and account_group_key is null and formula is null)
  ),
  constraint metrics_ledger_shape check (
    kind <> 'ledger' or (dataset_id is not null and account_group_key is not null
      and snapshot_rollup is null and base_metric_id is null and distinct_dimension_id is null
      and formula is null)
  ),
  constraint metrics_formula_shape check (
    kind <> 'formula' or (formula is not null and dataset_id is null and snapshot_rollup is null
      and base_metric_id is null and distinct_dimension_id is null and account_group_key is null)
  )
);
create index metrics_dataset_idx on public.metrics (dataset_id);
create index metrics_base_metric_idx on public.metrics (base_metric_id);
create index metrics_distinct_dimension_idx on public.metrics (distinct_dimension_id);
create index metrics_account_group_idx on public.metrics (account_group_key);

create table public.settings (
  key text primary key check (key ~ '^[a-z][a-z0-9_]{1,60}$'),
  value jsonb not null,
  updated_at timestamptz not null default now()
);
create trigger settings_touch
  before update on public.settings
  for each row execute function private.touch_updated_at();

-- RLS: allowlisted users read and edit reference data; deleting is limited to
-- aliases and account ranges (everything else is referenced by facts).
do $$
declare
  v_table text;
begin
  foreach v_table in array array[
    'companies', 'datasets', 'dimensions', 'dataset_dimensions', 'dimension_values',
    'dimension_aliases', 'account_groups', 'account_group_ranges', 'metrics', 'settings'
  ] loop
    execute format('alter table public.%I enable row level security', v_table);
    execute format('revoke all on public.%I from anon, authenticated', v_table);
    execute format('grant select, insert, update on public.%I to authenticated', v_table);
    execute format(
      'create policy "app users select" on public.%I for select to authenticated using ((select private.is_app_user()))',
      v_table);
    execute format(
      'create policy "app users insert" on public.%I for insert to authenticated with check ((select private.is_app_user()))',
      v_table);
    execute format(
      'create policy "app users update" on public.%I for update to authenticated using ((select private.is_app_user())) with check ((select private.is_app_user()))',
      v_table);
  end loop;

  foreach v_table in array array['dimension_aliases', 'account_group_ranges'] loop
    execute format('grant delete on public.%I to authenticated', v_table);
    execute format(
      'create policy "app users delete" on public.%I for delete to authenticated using ((select private.is_app_user()))',
      v_table);
  end loop;
end;
$$;

revoke execute on all functions in schema private from public;
